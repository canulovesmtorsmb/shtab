// Повтор случая 29.10: новое устройство с демо-базой подключается к облаку с настоящей базой через «Слить с облаком».
const { chromium } = require("playwright");
const fs = require("fs");
const APP = "http://127.0.0.1:8000/index.html", WORKER = "http://127.0.0.1:8787";
const KEY = "FreshSpace_" + Math.random().toString(36).slice(2, 10) + "_abcdefgh";
let fails = 0; const ok = (c, m) => { console.log((c ? "  OK   " : "  FAIL ") + m); if (!c) fails++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function device(b, url) {
  const ctx = await b.newContext({ timezoneId: "Asia/Bishkek" }); const page = await ctx.newPage(); const errs = [];
  page.on("pageerror", (e) => errs.push(e.message));
  await page.goto(APP);
  await page.waitForFunction(() => localStorage.getItem("shtab-base-202606") === "1" && localStorage.getItem("shtab-fresh-202606") === "1", null, { timeout: 60000 });
  await sleep(5000);
  return { ctx, page, errs };
}
(async () => {
  const b = await chromium.launch();
  const bk = JSON.parse(fs.readFileSync(__dirname + "/backup.json", "utf8"));
  console.log("1. Компьютер: своя база в облаке");
  const A = await device(b);
  await A.page.evaluate((t) => doImportFile(new File([t], "b.json")), JSON.stringify(bk));
  await A.page.waitForFunction((n) => (state.cache.lessons || []).length === n, bk.data.lessons.length, { timeout: 60000 });
  const ra = await A.page.evaluate(async ({ key, url }) => { const c = syncCfg(); c.key = key; c.url = url; syncSave(c); await syncJoin(key, true); await syncNow(); return { err: window._syncState.err, dirty: syncDirtyCount(), seeded: localStorage.getItem("shtab-seeded-at") }; }, { key: KEY, url: WORKER });
  ok(!ra.err && ra.dirty === 0 && !ra.seeded, "компьютер отправил свою базу (после импорта метка демо-базы снята)");
  const st0 = await (await fetch(`${WORKER}/v2/stats?space=${KEY}`)).json();
  const real = bk.data.students.find((s) => s.id === "c5705d73-ce");
  console.log("2. Новое устройство открывает ссылку и жмёт «Слить с облаком»");
  const B = await device(b);
  await B.page.evaluate((url) => { const c = syncCfg(); c.url = url; syncSave(c); }, WORKER);
  await B.page.goto("about:blank"); await B.page.goto(APP + "#key=" + KEY);
  await B.page.waitForFunction(() => typeof db !== "undefined" && db && state.cache.lessons); await sleep(2500);
  ok(/пока нет ваших записей/.test(await B.page.evaluate(() => document.body.innerText)), "окно предупреждает про демо-базу");
  await B.page.click('button:has-text("Слить с облаком")'); await sleep(5000);
  const st1 = await (await fetch(`${WORKER}/v2/stats?space=${KEY}`)).json();
  ok(JSON.stringify(st1.counts) === JSON.stringify(st0.counts), "состав облака не изменился: " + JSON.stringify(st1.counts));
  const names = await A.page.evaluate(async () => { await syncNow(); return (state.cache.students.find((s) => s.id === "c5705d73-ce") || {}).name; });
  ok(names === real.name, "на компьютере карточка не перетёрта демо-версией: «" + names + "»");
  const onB = await B.page.evaluate(() => ({ name: (state.cache.students.find((s) => s.id === "c5705d73-ce") || {}).name, n: state.cache.lessons.length, err: window._syncState.err }));
  ok(onB.name === real.name && !onB.err, "новое устройство получило настоящую карточку: «" + onB.name + "»");
  console.log("2б. Третье новое устройство: «Только забрать облако»");
  const C = await device(b);
  await C.page.evaluate((url) => { const c = syncCfg(); c.url = url; syncSave(c); }, WORKER);
  await C.page.goto("about:blank"); await C.page.goto(APP + "#key=" + KEY);
  await C.page.waitForFunction(() => typeof db !== "undefined" && db && state.cache.lessons); await sleep(2500);
  await C.page.click('button:has-text("Только забрать облако")'); await sleep(5000);
  const stC = await (await fetch(`${WORKER}/v2/stats?space=${KEY}`)).json();
  const onC = await C.page.evaluate(() => ({ name: (state.cache.students.find((s) => s.id === "c5705d73-ce") || {}).name, dirty: syncDirtyCount() }));
  const ch = await (await fetch(`${WORKER}/v2/pull?space=${KEY}&r=${st1.rev}&s=&i=`)).json();
  console.log("   ревизии: st0", st0.rev, "st1", st1.rev, "stC", stC.rev, "строк после st1:", ch.rows.length, JSON.stringify(ch.rows.filter((x) => x.r > st1.rev).map((x) => [x.s, x.i, x.r, x.u])).slice(0, 600));
  const after = ch.rows.filter((x) => x.r > st1.rev);
  const fromA = await A.page.evaluate((rows) => rows.every((x) => { const l = (state.cache[x.s] || []).find((y) => String(y.id) === x.i); return l && recU(l) === x.u; }), after);
  ok(fromA && onC.name === real.name && onC.dirty === 0, "после подключения C в облаке только правки компьютера (" + after.length + ", автозакрытие), на C настоящая карточка «" + onC.name + "»");
  console.log("3. Своя правка на новом устройстве уходит в облако");
  const own = await B.page.evaluate(async () => { const l = { id: "own-1", date: "2026-11-20", time: "12:00", status: "planned", topic: "своё", createdAt: Date.now() + 180000, updatedAt: Date.now() + 180000 }; await dbPut("lessons", l); await syncNow(); return { dirty: syncDirtyCount(), err: window._syncState.err }; });
  const st2 = await (await fetch(`${WORKER}/v2/stats?space=${KEY}`)).json();
  ok(!own.err && own.dirty === 0 && st2.counts.lessons === st0.counts.lessons + 1, "новое занятие дошло до облака: " + st2.counts.lessons);
  ok(A.errs.length === 0 && B.errs.length === 0, "ошибок страницы нет");
  await b.close();
  console.log(fails ? `\nПРОВАЛОВ: ${fails}` : "\nДЕМО-БАЗА НОВОГО УСТРОЙСТВА В ОБЛАКО НЕ ПОПАДАЕТ");
  process.exit(fails ? 1 : 0);
})();
